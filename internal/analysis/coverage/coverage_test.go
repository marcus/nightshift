package coverage

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("write %s: %v", path, err)
	}
}

func findPkg(r *OverallCoverage, dir string) *PackageCoverage {
	for i := range r.Packages {
		if r.Packages[i].Dir == dir {
			return &r.Packages[i]
		}
	}
	return nil
}

func TestAnalyzer_EmptyPackage(t *testing.T) {
	root := t.TempDir()
	writeFile(t, filepath.Join(root, "empty", "doc.go"), `// Package empty has no functions.
package empty
`)

	r, err := New(Options{Root: root}).Analyze()
	if err != nil {
		t.Fatalf("analyze: %v", err)
	}
	if r.TotalFuncs != 0 {
		t.Fatalf("expected 0 total funcs, got %d", r.TotalFuncs)
	}
	if r.Percent != 0 {
		t.Fatalf("expected 0%% coverage, got %.1f", r.Percent)
	}
}

func TestAnalyzer_FullyInstrumented(t *testing.T) {
	root := t.TempDir()
	src := `package full

import "log"

func A() { log.Printf("a") }
func B() { log.Println("b") }
`
	writeFile(t, filepath.Join(root, "full", "f.go"), src)

	r, err := New(Options{Root: root}).Analyze()
	if err != nil {
		t.Fatalf("analyze: %v", err)
	}
	pc := findPkg(r, "full")
	if pc == nil {
		t.Fatalf("package not found in %+v", r.Packages)
	}
	if pc.TotalFuncs != 2 || pc.InstrumentedFuncs != 2 {
		t.Fatalf("want 2/2, got %d/%d", pc.InstrumentedFuncs, pc.TotalFuncs)
	}
	if pc.Percent != 100 {
		t.Fatalf("want 100%%, got %.1f", pc.Percent)
	}
	if len(pc.UninstrumentedFuncs) != 0 {
		t.Fatalf("unexpected gaps: %+v", pc.UninstrumentedFuncs)
	}
}

func TestAnalyzer_PartiallyInstrumented(t *testing.T) {
	root := t.TempDir()
	src := `package partial

import "log"

func A() { log.Printf("a") }
func B() int { return 1 }
func C(x int) int { return x + 1 }
`
	writeFile(t, filepath.Join(root, "partial", "p.go"), src)

	r, err := New(Options{Root: root}).Analyze()
	if err != nil {
		t.Fatalf("analyze: %v", err)
	}
	pc := findPkg(r, "partial")
	if pc == nil {
		t.Fatalf("package not found")
	}
	if pc.TotalFuncs != 3 || pc.InstrumentedFuncs != 1 {
		t.Fatalf("want 1/3, got %d/%d", pc.InstrumentedFuncs, pc.TotalFuncs)
	}
	if len(pc.UninstrumentedFuncs) != 2 {
		t.Fatalf("want 2 gaps, got %d", len(pc.UninstrumentedFuncs))
	}
	names := []string{pc.UninstrumentedFuncs[0].Name, pc.UninstrumentedFuncs[1].Name}
	if names[0] != "B" || names[1] != "C" {
		t.Fatalf("unexpected gap names: %v", names)
	}
}

func TestAnalyzer_TestFilesExcluded(t *testing.T) {
	root := t.TempDir()
	writeFile(t, filepath.Join(root, "x", "x.go"), `package x
func A() {}
`)
	writeFile(t, filepath.Join(root, "x", "x_test.go"), `package x
import "testing"
func TestA(t *testing.T) {}
`)

	r, err := New(Options{Root: root}).Analyze()
	if err != nil {
		t.Fatalf("analyze: %v", err)
	}
	pc := findPkg(r, "x")
	if pc == nil || pc.TotalFuncs != 1 {
		t.Fatalf("want 1 func, got %+v", pc)
	}

	// Re-run including tests.
	r2, err := New(Options{Root: root, IncludeTests: true}).Analyze()
	if err != nil {
		t.Fatalf("analyze: %v", err)
	}
	pc2 := findPkg(r2, "x")
	if pc2 == nil || pc2.TotalFuncs != 2 {
		t.Fatalf("want 2 funcs with tests, got %+v", pc2)
	}
}

func TestAnalyzer_VendoredAndGeneratedExcluded(t *testing.T) {
	root := t.TempDir()
	writeFile(t, filepath.Join(root, "vendor", "lib", "lib.go"), `package lib
func V() {}
`)
	writeFile(t, filepath.Join(root, "gen", "x_generated.go"), `package gen
func G() {}
`)
	writeFile(t, filepath.Join(root, "gen", "marker.go"), `// Code generated by tool; DO NOT EDIT.
package gen
func M() {}
`)
	writeFile(t, filepath.Join(root, "good", "g.go"), `package good
import "log"
func H() { log.Print("ok") }
`)

	r, err := New(Options{Root: root}).Analyze()
	if err != nil {
		t.Fatalf("analyze: %v", err)
	}
	if findPkg(r, filepath.Join("vendor", "lib")) != nil {
		t.Fatalf("vendor/lib should be skipped")
	}
	gen := findPkg(r, "gen")
	if gen != nil && gen.TotalFuncs > 0 {
		t.Fatalf("generated files should be skipped, got %+v", gen)
	}
	good := findPkg(r, "good")
	if good == nil || good.TotalFuncs != 1 || good.InstrumentedFuncs != 1 {
		t.Fatalf("want 1/1 in good, got %+v", good)
	}
}

func TestAnalyzer_ExcludePatterns(t *testing.T) {
	root := t.TempDir()
	writeFile(t, filepath.Join(root, "skipme", "s.go"), `package skipme
func S() {}
`)
	writeFile(t, filepath.Join(root, "keep", "k.go"), `package keep
func K() {}
`)

	r, err := New(Options{Root: root, Excludes: []string{"skipme/**"}}).Analyze()
	if err != nil {
		t.Fatalf("analyze: %v", err)
	}
	if findPkg(r, "skipme") != nil {
		t.Fatalf("skipme should be excluded")
	}
	if findPkg(r, "keep") == nil {
		t.Fatalf("keep should remain")
	}
}

func TestAnalyzer_CustomPatterns(t *testing.T) {
	root := t.TempDir()
	src := `package c
func A() { myMetric("a") }
func B() { other("b") }
func myMetric(s string) {}
func other(s string) {}
`
	writeFile(t, filepath.Join(root, "c", "c.go"), src)
	r, err := New(Options{Root: root, Patterns: []string{"myMetric"}}).Analyze()
	if err != nil {
		t.Fatalf("analyze: %v", err)
	}
	pc := findPkg(r, "c")
	if pc == nil {
		t.Fatalf("package missing")
	}
	if pc.InstrumentedFuncs != 1 {
		t.Fatalf("want 1 instrumented, got %d", pc.InstrumentedFuncs)
	}
}

func TestAnalyzer_MethodReceiverDisplay(t *testing.T) {
	root := t.TempDir()
	src := `package r
type T struct{}
func (t *T) Do() { x() }
func x() {}
`
	writeFile(t, filepath.Join(root, "r", "r.go"), src)
	r, err := New(Options{Root: root}).Analyze()
	if err != nil {
		t.Fatalf("analyze: %v", err)
	}
	pc := findPkg(r, "r")
	if pc == nil {
		t.Fatalf("package missing")
	}
	foundMethod := false
	for _, g := range pc.UninstrumentedFuncs {
		if strings.Contains(g.Name, "(T).Do") {
			foundMethod = true
		}
	}
	if !foundMethod {
		t.Fatalf("expected method gap with receiver, got %+v", pc.UninstrumentedFuncs)
	}
}
